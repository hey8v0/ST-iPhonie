"""Generate the Phase 2 Termux bundle and unsigned AMO submission XPI."""
from gzip import compress
from hashlib import sha256
from io import BytesIO
from pathlib import Path
import base64
import json
import tarfile
import textwrap
import zipfile

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "termux" / "browser-bridge"
OUTPUT = ROOT / "tools" / "browser-bridge" / "ST-iPhonie-Browser-Phase2.sh"
VERSION = json.loads((SOURCE / "extension/manifest.json").read_text("utf-8"))["version"]
XPI = OUTPUT.with_name(f"iPhonie-Browser-Bridge-{VERSION}.xpi")

INSTALL = """#!/data/data/com.termux/files/usr/bin/bash
# Generated by tools/browser-bridge/build.py
set -euo pipefail
umask 077
if ! command -v node >/dev/null || ! node -e 'process.exit(typeof fetch === "function" && typeof AbortSignal.timeout === "function" ? 0 : 1)'; then
  echo '此实验包需要现有 iphonie-browser 所用的 Node.js（18 或以上）。'
  exit 1
fi
if [[ -z "${PREFIX:-}" || ! -x "$PREFIX/bin/sh" ]]; then
  echo '请在 Termux 中运行此安装包。'
  exit 1
fi
base="$HOME/.local/share/st-iphonie-bridge"
mkdir -p "$base/bundles"
chmod 700 "$base"
if ! command -v flock >/dev/null; then
  echo '请先完成现有 iphonie-browser 的安装，再运行实验包。'
  exit 1
fi
exec 9>"$base/install.lock"
flock -w 15 9 || { echo '另一次实验包安装正在进行，请稍后重试。'; exit 1; }
stage="$(mktemp -d "$base/.install.XXXXXX")"
archive="$stage/payload.tar.gz"
cleanup() {
  local real_stage real_base
  real_stage="$(cd "$stage" && pwd -P)" || return
  real_base="$(cd "$base" && pwd -P)" || return
  if [[ "$real_stage" == "$real_base"/.install.* ]]; then rm -rf -- "$real_stage"; fi
}
trap cleanup EXIT
base64 -d > "$archive" <<'IPH_PAYLOAD'
@PAYLOAD@
IPH_PAYLOAD
sum=@HASH@
if [[ "$(sha256sum "$archive" | cut -d' ' -f1)" != "$sum" ]]; then
  echo '安装包完整性检查失败，请重新下载实验包。'
  exit 1
fi
target="$base/bundles/$sum"
if [[ ! -d "$target" ]]; then
  mkdir "$stage/bundle"
  tar -xz -C "$stage/bundle" -f "$archive"
  if ! mv -T "$stage/bundle" "$target"; then
    echo '实验包安装目录冲突，请重新运行安装命令。'
    exit 1
  fi
fi
node "$target/cli.cjs" install 9>&-
if [[ "${1:-}" == --plugin ]]; then
  node "$target/cli.cjs" plugin "${2:-}" "${3:-}" 9>&-
fi
"""


def main():
    extension = BytesIO()
    with zipfile.ZipFile(extension, "w", compression=zipfile.ZIP_DEFLATED) as xpi:
        for file in sorted((SOURCE / "extension").iterdir()):
            info = zipfile.ZipInfo(file.name)
            info.compress_type = zipfile.ZIP_DEFLATED
            xpi.writestr(info, file.read_bytes().replace(b"\r\n", b"\n"))
    archive = BytesIO()
    XPI.write_bytes(extension.getvalue())
    with tarfile.open(fileobj=archive, mode="w", format=tarfile.USTAR_FORMAT) as tar:
        files = {file.relative_to(SOURCE).as_posix(): file.read_bytes().replace(b"\r\n", b"\n")
                 for file in sorted(SOURCE.rglob("*")) if file.is_file()}
        files["iPhonie-Browser-Bridge.xpi"] = extension.getvalue()
        for name, content in files.items():
            info = tarfile.TarInfo(name)
            info.size = len(content)
            info.mode = 0o600
            tar.addfile(info, BytesIO(content))
    payload = compress(archive.getvalue(), mtime=0)
    encoded = "\n".join(textwrap.wrap(base64.b64encode(payload).decode(), 76))
    OUTPUT.write_bytes(INSTALL.replace("@HASH@", sha256(payload).hexdigest()).replace("@PAYLOAD@", encoded).encode())


if __name__ == "__main__":
    main()
