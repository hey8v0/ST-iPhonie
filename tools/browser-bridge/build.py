"""Verify Mozilla's XPI and build a commit-pinned Termux installer."""
from argparse import ArgumentParser
from gzip import compress
from hashlib import sha256
from io import BytesIO
from pathlib import Path
import base64
import json
import re
import subprocess
import tarfile
import textwrap
import zipfile

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "termux" / "browser-bridge"
OUTPUT = ROOT / "tools" / "browser-bridge" / "ST-iPhonie-Browser-Phase2.sh"
VERSION = json.loads((SOURCE / "extension/manifest.json").read_text("utf-8"))["version"]
RELEASE = json.loads((SOURCE / "release.json").read_text("utf-8"))
SIGNATURE = OUTPUT.with_name(f"iPhonie-Browser-Bridge-{VERSION}-signed.xpi")

INSTALL = """#!/data/data/com.termux/files/usr/bin/bash
# Generated by tools/browser-bridge/build.py
set -euo pipefail
umask 077
if ! command -v node >/dev/null || ! node -e 'process.exit(typeof fetch === "function" && typeof AbortSignal.timeout === "function" ? 0 : 1)'; then
  echo '此实验包需要现有 iphonie-browser 所用的 Node.js（18 或以上）。'
  exit 1
fi
if [[ -z "${PREFIX:-}" || ! -x "$PREFIX/bin/sh" ]]; then
  echo '请在 Termux 中运行此安装包。'
  exit 1
fi
base="$HOME/.local/share/st-iphonie-bridge"
mkdir -p "$base/bundles"
chmod 700 "$base"
if ! command -v flock >/dev/null; then
  echo '请先完成现有 iphonie-browser 的安装，再运行实验包。'
  exit 1
fi
exec 9>"$base/install.lock"
flock -w 15 9 || { echo '另一次实验包安装正在进行，请稍后重试。'; exit 1; }
stage="$(mktemp -d "$base/.install.XXXXXX")"
archive="$stage/payload.tar.gz"
cleanup() {
  local real_stage real_base
  real_stage="$(cd "$stage" && pwd -P)" || return
  real_base="$(cd "$base" && pwd -P)" || return
  if [[ "$real_stage" == "$real_base"/.install.* ]]; then rm -rf -- "$real_stage"; fi
}
trap cleanup EXIT
base64 -d > "$archive" <<'IPH_PAYLOAD'
@PAYLOAD@
IPH_PAYLOAD
sum=@HASH@
if [[ "$(sha256sum "$archive" | cut -d' ' -f1)" != "$sum" ]]; then
  echo '安装包完整性检查失败，请重新下载实验包。'
  exit 1
fi
target="$base/bundles/$sum"
if [[ ! -d "$target" ]]; then
  mkdir "$stage/bundle"
  tar -xz -C "$stage/bundle" -f "$archive"
  if ! mv -T "$stage/bundle" "$target"; then
    echo '实验包安装目录冲突，请重新运行安装命令。'
    exit 1
  fi
fi
node "$target/cli.cjs" install "${1:---plugin}" "${2:-}" "${3:-}" 9>&-
"""


def code():
    return {file.name: file.read_bytes().replace(b"\r\n", b"\n")
            for file in sorted((SOURCE / "extension").iterdir()) if file.is_file()}


def unsigned_xpi():
    extension = BytesIO()
    with zipfile.ZipFile(extension, "w", compression=zipfile.ZIP_DEFLATED) as xpi:
        for name, data in code().items():
            info = zipfile.ZipInfo(name)
            info.compress_type = zipfile.ZIP_DEFLATED
            xpi.writestr(info, data)
    return extension.getvalue()


def verify_signed(data, require_digest=True):
    digest = sha256(data).hexdigest()
    if require_digest and digest != RELEASE["signedSha256"]:
        raise ValueError("Signed XPI SHA-256 does not match release.json")
    sources = code()
    protocol = re.search(rb"\bconst version = (\d+);", sources["protocol.js"])
    if not protocol or int(protocol[1]) != RELEASE["protocol"] or VERSION not in RELEASE["compatibleExtensions"]:
        raise ValueError("Extension protocol is missing from the compatibility declaration")
    with zipfile.ZipFile(BytesIO(data)) as xpi:
        members = xpi.namelist()
        expected = {name for name in members if not name.startswith("META-INF/")}
        signed_metadata = {"META-INF/manifest.mf", "META-INF/mozilla.sf", "META-INF/mozilla.rsa"}
        if (len(set(members)) != len(members) or xpi.testzip() or expected != sources.keys()
                or not signed_metadata.issubset(members)):
            raise ValueError("Signed XPI contents are invalid")
        for name, source in sources.items():
            candidate = xpi.read(name)
            if name == "manifest.json":
                manifest = json.loads(candidate)
                if (manifest != json.loads(source) or manifest["version"] != RELEASE["extension"]
                        or manifest["browser_specific_settings"]["gecko"]["id"] != RELEASE["extensionId"]
                        or "update_url" in manifest["browser_specific_settings"]["gecko"]):
                    raise ValueError("Signed manifest differs from source or coordinated release settings")
            elif candidate != source:
                raise ValueError(f"Signed XPI differs from source: {name}")
    return digest


def installer(frontend, signed):
    if not re.fullmatch(r"[a-f0-9]{40}", frontend):
        raise ValueError("Use the full Git commit SHA for the matching frontend")
    verify_signed(signed)
    archive = BytesIO()
    with tarfile.open(fileobj=archive, mode="w", format=tarfile.USTAR_FORMAT) as tar:
        files = {file.relative_to(SOURCE).as_posix(): file.read_bytes().replace(b"\r\n", b"\n")
                 for file in sorted(SOURCE.rglob("*")) if file.is_file()}
        files["iPhonie-Browser-Bridge-signed.xpi"] = signed
        files["bundle-release.json"] = (json.dumps({**RELEASE, "frontend": frontend}, indent=2) + "\n").encode()
        for name, content in files.items():
            info = tarfile.TarInfo(name)
            info.size = len(content)
            info.mode = 0o600
            tar.addfile(info, BytesIO(content))
    payload = compress(archive.getvalue(), mtime=0)
    encoded = "\n".join(textwrap.wrap(base64.b64encode(payload).decode(), 76))
    return INSTALL.replace("@HASH@", sha256(payload).hexdigest()).replace("@PAYLOAD@", encoded).encode()


def verify_checkout(frontend):
    if not re.fullmatch(r"[a-f0-9]{40}", frontend):
        raise ValueError("Use the full Git commit SHA for the matching frontend")
    ui = ("ui/browser.js", "ui/browser-phase2.js", "ui/browser-phase2-link.js", "ui/browser.css")
    files = [*(ROOT / name for name in ui), *(file for file in SOURCE.rglob("*") if file.is_file())]
    for file in files:
        relative = file.relative_to(ROOT).as_posix()
        committed = subprocess.check_output(
            ["git", "-c", f"safe.directory={ROOT.as_posix()}", "-C", ROOT, "show", f"{frontend}:{relative}"]
        )
        if committed != file.read_bytes().replace(b"\r\n", b"\n"):
            raise ValueError(f"Checkout differs from the pinned frontend commit: {relative}")


def main():
    parser = ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--frontend", help="Build signed installer for this Git commit")
    mode.add_argument("--unsigned", action="store_true", help="Build a developer XPI only")
    mode.add_argument("--verify-signed", action="store_true", help="Compare AMO output to source and print its SHA-256")
    parser.add_argument("--signed", type=Path, default=SIGNATURE)
    parser.add_argument("--output-dir", type=Path, default=OUTPUT.parent)
    args = parser.parse_args()
    if args.verify_signed:
        print(verify_signed(args.signed.read_bytes(), require_digest=False))
        return
    args.output_dir.mkdir(parents=True, exist_ok=True)
    if args.unsigned:
        (args.output_dir / f"iPhonie-Browser-Bridge-{VERSION}.xpi").write_bytes(unsigned_xpi())
    else:
        verify_checkout(args.frontend)
        (args.output_dir / OUTPUT.name).write_bytes(installer(args.frontend, args.signed.read_bytes()))


if __name__ == "__main__":
    main()
